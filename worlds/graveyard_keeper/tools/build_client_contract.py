from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any


WORLD_ROOT = Path(__file__).resolve().parents[1]
DATA_ROOT = WORLD_ROOT / "data"
DEFAULT_OUTPUT = DATA_ROOT / "client_contract.json"


def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def _load_items(data_root: Path) -> dict[str, dict[str, Any]]:
    items: dict[str, dict[str, Any]] = {}
    item_root = data_root / "items"
    for path in sorted(item_root.rglob("*.json")):
        if "unused" in path.parts:
            continue
        for item_key, item in _load_json(path).items():
            if item_key in items:
                raise ValueError(f"Item '{item_key}' is defined more than once")
            items[item_key] = item
    return items


def _load_locations(
    data_root: Path,
    regions: dict[str, dict[str, Any]],
) -> dict[str, dict[str, Any]]:
    locations = _load_json(data_root / "locations.json")

    # These locations are generated by data.load_locations() at APWorld import
    # time rather than being duplicated in locations.json.  They are still part
    # of the public network-location contract and therefore must be exported.
    for region_key, region in regions.items():
        if not region_key.startswith("REGION_TECH_TREE") or "/" not in region_key:
            continue

        region_subname = region_key.rsplit("/", 1)[1]
        for unlock_index in range(1, 4):
            if "SPIRITUALISM" in region_key and region_key.endswith("_GRAVESTONES"):
                location_key = f"LOCATION_{region_subname}_SPIRITUALISM_UNLOCK_{unlock_index}"
                label = f"{region['label']} - Unlock {unlock_index} (Spiritualism)"
            else:
                location_key = f"LOCATION_{region_subname}_UNLOCK_{unlock_index}"
                label = f"{region['label']} - Unlock {unlock_index}"

            generated = {"label": label, "parent_region": region_key}
            if location_key in locations and locations[location_key] != generated:
                raise ValueError(f"Generated location '{location_key}' conflicts with locations.json")
            locations[location_key] = generated

    return locations


def _require_unique_names(entries: dict[str, dict[str, Any]], entry_type: str) -> None:
    names = [entry["label"] for entry in entries.values()]
    duplicates = sorted(name for name, count in Counter(names).items() if count > 1)
    if duplicates:
        raise ValueError(f"Duplicate {entry_type} network names: {duplicates}")


def build_client_contract(data_root: Path = DATA_ROOT) -> dict[str, Any]:
    items = _load_items(data_root)
    grants = _load_json(data_root / "item_grants.json")
    triggers = _load_json(data_root / "quest_reward_triggers.json")
    regions = _load_json(data_root / "regions.json")
    locations = _load_locations(data_root, regions)

    if items.keys() != grants.keys():
        missing = sorted(items.keys() - grants.keys())
        unexpected = sorted(grants.keys() - items.keys())
        raise ValueError(f"Item grant mismatch; missing={missing}, unexpected={unexpected}")
    unexpected_triggers = sorted(triggers.keys() - locations.keys())
    if unexpected_triggers:
        raise ValueError(f"Triggers reference unknown locations: {unexpected_triggers}")

    _require_unique_names(items, "item")
    _require_unique_names(locations, "location")

    contract_items = {
        item_key: {
            "name": item["label"],
            "dlc": item["dlc"],
            "classification": item["classification"],
            "amount": item.get("amount", 1),
            "grant": grants[item_key],
        }
        for item_key, item in items.items()
    }
    contract_locations = {
        location_key: {
            "name": location["label"],
            "dlc": regions[location["parent_region"]]["dlc"],
            "parent_region": location["parent_region"],
            "triggers": triggers.get(location_key, []),
        }
        for location_key, location in locations.items()
    }

    return {
        "schema_version": 1,
        "game": "Graveyard Keeper",
        "items": contract_items,
        "locations": contract_locations,
    }


def write_client_contract(output: Path, data_root: Path = DATA_ROOT) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    serialized = json.dumps(build_client_contract(data_root), indent=2, ensure_ascii=False) + "\n"
    output.write_text(serialized, encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the Graveyard Keeper APWorld/client data contract")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--client-output",
        type=Path,
        help="Optional second generated copy for the companion client repository",
    )
    args = parser.parse_args()

    write_client_contract(args.output)
    if args.client_output is not None:
        write_client_contract(args.client_output)


if __name__ == "__main__":
    main()
