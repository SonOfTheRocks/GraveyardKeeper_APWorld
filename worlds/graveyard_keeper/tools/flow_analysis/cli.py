from __future__ import annotations

import argparse
import sys
from pathlib import Path

from .analysis import AnalysisLimits, analyze_graph
from .graph_report import build_game_data_script_index, load_quest_node_names
from .mapping import APWorldIndex
from .parser import FlowGraphParseError, parse_graph
from .report import write_reports
from .summaries import build_phrase_unlock_index


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Analyze Graveyard Keeper FlowGraph JSON and write Markdown reports")
    parser.add_argument("input", type=Path, help="directory containing FlowGraph *.json exports")
    parser.add_argument("output", type=Path, help="directory receiving README.md and per-graph reports")
    parser.add_argument("--graph", action="append", default=[], help="case-insensitive graph filename/stem filter; repeatable")
    parser.add_argument("--npc", action="append", default=[], help="alias for --graph; filters filename/stem, not proven NPC identity")
    parser.add_argument("--item", help="case-insensitive reward item/resource substring")
    parser.add_argument("--node", help="exact local reward node id")
    parser.add_argument("--target-type", choices=("item", "relation"), help="reward target type")
    parser.add_argument("--max-paths", type=int, default=32)
    parser.add_argument("--max-depth", type=int, default=200)
    parser.add_argument("--max-states", type=int, default=10_000)
    parser.add_argument("--apworld-data", type=Path, help="optional worlds/graveyard_keeper/data directory for key suggestions")
    parser.add_argument("--game-data", type=Path,
                        help="optional vanilla GameData dump directory for external script triggers")
    parser.add_argument("--details", action="store_true",
                        help="include technical references, evidence paths, and uncertainties")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if min(args.max_paths, args.max_depth, args.max_states) < 1:
        raise SystemExit("analysis limits must be positive")
    filters = [entry.casefold() for entry in args.graph + args.npc]
    all_paths = sorted(args.input.glob("*.json"), key=lambda path: path.name.casefold())
    selected_paths = all_paths
    if filters:
        selected_paths = [path for path in all_paths if any(
            token in path.stem.casefold() or token in path.name.casefold() for token in filters)]
    all_analyses = []
    all_errors: list[tuple[Path, str]] = []
    limits = AnalysisLimits(args.max_paths, args.max_depth, args.max_states)
    for path in all_paths:
        try:
            all_analyses.append(analyze_graph(parse_graph(path), limits))
        except FlowGraphParseError as error:
            all_errors.append((path, str(error)))
    selected_names = {path.stem for path in selected_paths}
    analyses = [analysis for analysis in all_analyses if analysis.graph.name in selected_names]
    errors = [message for path, message in all_errors if path.stem in selected_names]
    apworld = APWorldIndex(args.apworld_data)
    report_filters = {"item": args.item, "node": args.node, "target_type": args.target_type}
    marker = args.output / ".flow-analysis-output"
    previously_owned = marker.exists()
    written = write_reports(args.output, analyses, errors, apworld, report_filters, details=args.details,
                            phrase_unlocks=build_phrase_unlock_index(all_analyses),
                            game_data_scripts=build_game_data_script_index(args.game_data),
                            node_names=load_quest_node_names(
                                Path(__file__).parent / "data" / "quest_node_names.json"))
    if previously_owned:
        for path in [*args.output.glob("*.md"), *args.output.glob("*.html")]:
            if path.name not in written:
                path.unlink()
    marker.write_text("Generated by Graveyard Keeper flow_analysis.\n", encoding="utf-8")
    report_count = sum(name.endswith(".md") for name in written) - 3
    print(f"Analyzed {len(analyses)} graph(s), wrote {report_count} compact graph report(s) and QUEST_GRAPH.html, "
          f"encountered {len(errors)} unreadable file(s). Reports: {args.output}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
